#!/usr/bin/env python3
"""Build every Goldfelty icon from the one logo file.

The source is resources/logo.png: a 1024px rounded tile with the serif G and
gold dot. This writes the sizes each place needs. It uses ImageMagick
(`magick`, or `convert` on older installs) for the resizing.

  resources/icon.png        Windows and Linux app icon (full tile, 1024px)
  resources/icon-mac.png    macOS app icon, inset on Apple's 824px grid so it
                            sits the same size as other apps in the Dock
  resources/icons/NxN.png   Linux icon sizes
  site/icon.png             goldfelty.com favicon
  site/mark.png             goldfelty.com header mark
  src/renderer/src/assets/mark.png   the mark inside the app
  src/main/connections/bridgeMark.ts the mark on the wallet bridge page, as a
                                     data: URI (that page may load nothing else)
"""
import base64
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "resources" / "logo.png"


def magick():
    for name in ("magick", "convert"):
        path = shutil.which(name)
        if path:
            return path
    raise SystemExit("ImageMagick is needed: install it so `magick` or `convert` is on PATH")


TOOL = magick()


def run(*args):
    subprocess.run([TOOL, *map(str, args)], check=True)


def resized(out, size):
    out.parent.mkdir(parents=True, exist_ok=True)
    run(SOURCE, "-filter", "Lanczos", "-resize", f"{size}x{size}", "-strip", out)
    print(f"wrote {out.relative_to(ROOT)} ({size}px)")


def mac_icon(out):
    # Apple's icon grid: the tile is 824px inside a 1024px canvas.
    run(
        SOURCE, "-filter", "Lanczos", "-resize", "824x824",
        "-background", "none", "-gravity", "center", "-extent", "1024x1024",
        "-strip", out,
    )
    print(f"wrote {out.relative_to(ROOT)} (1024px, inset)")


def bridge_mark(out):
    with tempfile.TemporaryDirectory() as tmp:
        png = Path(tmp) / "mark.png"
        run(SOURCE, "-filter", "Lanczos", "-resize", "64x64", "-strip", png)
        data = base64.b64encode(png.read_bytes()).decode()
    out.write_text(
        "// Generated by scripts/make-icons.py from resources/logo.png. Do not edit.\n"
        f"export const BRIDGE_MARK = 'data:image/png;base64,{data}'\n"
    )
    print(f"wrote {out.relative_to(ROOT)} ({len(data)} chars)")


if __name__ == "__main__":
    if not SOURCE.exists():
        raise SystemExit(f"missing {SOURCE.relative_to(ROOT)}")
    resized(ROOT / "resources" / "icon.png", 1024)
    mac_icon(ROOT / "resources" / "icon-mac.png")
    for size in (512, 256, 128, 64, 48, 32, 16):
        resized(ROOT / "resources" / "icons" / f"{size}x{size}.png", size)
    resized(ROOT / "site" / "icon.png", 256)
    resized(ROOT / "site" / "mark.png", 96)
    resized(ROOT / "src" / "renderer" / "src" / "assets" / "mark.png", 128)
    bridge_mark(ROOT / "src" / "main" / "connections" / "bridgeMark.ts")
